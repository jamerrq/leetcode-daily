class Solution:
    def hasValidPath(self, grid: list[list[str]]) -> bool:
        n, m = len(grid), len(grid[0])

        # invalid cases
        if grid[0][0] != '(' or grid[-1][-1] != ')' or (m + n - 1) % 2:
            return False

        dp: list[int] = [0] * m
        left = n + m - 2

        for row in range(n):
            for col in range(m):
                char = grid[row][col]
                options = dp[col] | dp[col - 1] if col else dp[col]
                if not row:
                    options = dp[col - 1] if col else 1

                if char == '(':
                    dp[col] = options << 1
                    dp[col] &= ((1 << ((left - row - col) + 1)) - 1)
                else:
                    dp[col] = options >> 1

        return bool(dp[-1] & 1)

